_SAFE_NAME_RE = re.compile(r"[^\w.\-_]+", re.UNICODE)
_MAX_NAME_LEN = 180


@dataclass(frozen=True)
class StoredFile:
    """A2A-aligned file product metadata."""

    attachment_id: str
    name: str
    mime_type: str
    size_bytes: int
    url: str
    conversation_id: str | None = None
    previewable: bool = False


class FileStore(Protocol):
    def put(
        self,
        *,
        data: bytes,
        name: str,
        mime_type: str,
        conversation_id: str | None = None,
        # Provenance of the bytes; the closed vocabulary lives on
        # FileRecord.origin (upload/agent_created/browser_download/artifact_build).
        # The caller knows the provenance -- the store must not guess.
        origin: str = "upload",
    ) -> StoredFile: ...

    def get(self, attachment_id: str) -> StoredFile | None: ...

    def read_bytes(self, attachment_id: str) -> bytes | None: ...

    def exists(self, attachment_id: str) -> bool: ...

    def list(self) -> list[StoredFile]: ...

    def delete(self, attachment_id: str) -> bool:
        """Soft-delete: retire the file from reads/list; bytes stay recoverable.

        Returns True when the file transitioned to trashed, False when there
        was nothing to do (unknown id, no registry, or already trashed).
        """
        ...


def _safe_filename(name: str) -> str:
    base = Path(name).name.strip() or "file"
    cleaned = _SAFE_NAME_RE.sub("_", base).strip("._") or "file"
    return cleaned[:_MAX_NAME_LEN]


def write_sidecar_pair(
    meta_path: Path, blob_path: Path, meta: dict[str, object], blob: bytes
) -> None:
    """Write one id -> (meta.json + blob) sidecar pair (RA-176 shared ritual).

    Converges the twin hand-rolled pattern: the store's {attachment_id}/ dirs
    and trash's flat sidecar files both serialize a JSON meta file plus a
    raw-bytes blob addressed by an id. Layout (subdir vs flat) stays each
    caller's choice; the serialization ritual is owned here.
    """
    meta_path.parent.mkdir(parents=True, exist_ok=True)
    meta_path.write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    blob_path.write_bytes(blob)


def trash_dir_for(workspace_root: Path) -> Path:
    """Locate the .trash/ directory for a workspace root (shared rule).

    Historical TrashManager layout: <parent>/.trash when the root itself is
    named "workspace", else <root>/.trash. Both the store's delete ritual and
    the manager's restore/purge use this one rule.
    """
    root = Path(workspace_root).resolve()
    base = root.parent if root.name == "workspace" else root
    trash_dir = base / ".trash"
    trash_dir.mkdir(parents=True, exist_ok=True)
    return trash_dir


def file_part_from_stored(stored: StoredFile) -> dict[str, object]:
    """Canonical product part — one shape for plugin_state.files and ToolInvoked.files."""
    return {
        "name": stored.name,
        "mimeType": stored.mime_type,
        "sizeBytes": stored.size_bytes,
        "url": stored.url,
        "previewable": stored.previewable,
        "attachmentId": stored.attachment_id,
    }


def persist_generated_files(
    store: FileStore, files: Sequence[object], *, origin: str = "agent_created"
) -> list[dict[str, object]]:
    """Store harvested sandbox bytes once; return canonical file parts.

    Every caller harvests agent-generated bytes (office works, computer
    harvest, exec/lca_computer observations), so the default is
    "agent_created", not the store's "upload" fallback.
    """
    parts: list[dict[str, object]] = []
    for item in files:
        data = getattr(item, "data", None)
        name = getattr(item, "name", "")
        mime = getattr(item, "mime_type", "") or "application/octet-stream"
        if not isinstance(data, (bytes, bytearray)) or not name:
            continue
        parts.append(
            file_part_from_stored(
                store.put(data=bytes(data), name=str(name), mime_type=str(mime), origin=origin)
            )
        )
    return parts




class LocalFileStore:
    """Filesystem-backed FileStore with JSON sidecars and workspace/user/ alignment."""

    def __init__(
        self,
        root: Path | None = None,
        *,
        public_url_prefix: str = "/files",
        registry: Any = None,
    ) -> None:
        raw_root = (
            root if root is not None else assistant_workspace_root() / "uploads"
        ).resolve()
        # If root points to workspace directly, or an uploads subdir, determine workspace root
        if raw_root.name == "uploads":
            self._workspace_root = raw_root.parent
            self._legacy_root = raw_root
        else:
            self._workspace_root = raw_root
            self._legacy_root = raw_root / "uploads"
        self._root = self._legacy_root
        self._legacy_root.mkdir(parents=True, exist_ok=True)
        self._url_prefix = public_url_prefix.rstrip("/")
        self._registry = registry

    @property
    def root(self) -> Path:
        return self._root

    @property
    def workspace_root(self) -> Path:
        return self._workspace_root

    def put(
        self,
        *,
        data: bytes,
        name: str,
        mime_type: str,
        conversation_id: str | None = None,
        origin: str = "upload",
    ) -> StoredFile:
        attachment_id = new_id("file")
        safe_name = _safe_filename(name)
        mime = (mime_type or "application/octet-stream").strip() or "application/octet-stream"

        # 1. Physical placement into workspace/user/
        user_dir = self._workspace_root / "user"
        user_dir.mkdir(parents=True, exist_ok=True)

        dest_path = user_dir / safe_name
        final_name = safe_name
        if dest_path.exists():
            from datetime import datetime
            base, ext = os.path.splitext(safe_name)
            ts = datetime.now(UTC).strftime("%Y%m%d_%H%M%S")
            final_name = f"{base}_{ts}{ext}"
            dest_path = user_dir / final_name

        dest_path.write_bytes(data)

        # 2. Legacy mirror storage for backward-compatibility lookup by attachment_id
        # (RA-176: the id -> meta.json + blob write goes through the shared
        # sidecar helper, converging the twin hand-rolled pattern.)
        directory = self._legacy_root / attachment_id

        profile = readability_profile(final_name, mime)
        stored = StoredFile(
            attachment_id=attachment_id,
            name=final_name,
            mime_type=mime,
            size_bytes=len(data),
            url=f"{self._url_prefix}/{attachment_id}",
            conversation_id=conversation_id,
            previewable=profile.ui_preview,
        )
        write_sidecar_pair(directory / "meta.json", directory / "blob", asdict(stored), data)

        # 3. Register in SQLite FileIndexRegistry if present
        if self._registry is not None:
            from datetime import datetime
            now = datetime.now(UTC)
            record = FileRecord(
                file_id=attachment_id,
                path=f"user/{final_name}",
                origin=origin,
                visibility=VisibilityTier.INTERNAL,
                mime=mime,
                size_bytes=len(data),
                readability=profile.tier,
                created_at=now,
                updated_at=now,
                source_chat_id=conversation_id,
            )
            self._registry.register(record)

        return stored

    def _is_trashed(self, attachment_id: str) -> bool:
        """Trash state is registry-owned; without a registry nothing is trashed."""
        if self._registry is None:
            return False
        record = self._registry.get_by_id(attachment_id)
        return record is not None and record.trashed_at is not None

    def get(self, attachment_id: str) -> StoredFile | None:
        if self._is_trashed(attachment_id):
            return None
        meta_path = self._root / attachment_id / "meta.json"
        if not meta_path.is_file():
            return None
        try:
            raw = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return None
        try:
            return StoredFile(
                attachment_id=str(raw["attachment_id"]),
                name=str(raw["name"]),
                mime_type=str(raw["mime_type"]),
                size_bytes=int(raw["size_bytes"]),
                url=str(raw.get("url") or f"{self._url_prefix}/{attachment_id}"),
                conversation_id=raw.get("conversation_id"),
                previewable=bool(raw.get("previewable", False)),
            )
        except (KeyError, TypeError, ValueError):
            return None

    def read_bytes(self, attachment_id: str) -> bytes | None:
        if self._is_trashed(attachment_id):
            return None
        blob = self._root / attachment_id / "blob"
        if not blob.is_file():
            return None
        return blob.read_bytes()

    def exists(self, attachment_id: str) -> bool:
        # RA-179: the read surface must agree -- get()/read_bytes()/list()
        # go dark on trashed files, so exists() (which every consumer reads
        # as "is this file still usable") does too. Fail-closed.
        if self._is_trashed(attachment_id):
            return False
        return (self._root / attachment_id / "meta.json").is_file()

    def delete(self, attachment_id: str) -> bool:
        """Soft-delete through the FileStore interface (RA-176).

        Ritual: resolve the registry record -> retire the live workspace copy
        into a .trash/ sidecar (shared sidecar helper) -> flag trashed_at in
        the registry. The {attachment_id}/ mirror (meta.json + blob) is
        deliberately KEPT: the /files/{attachment_id} stable address and its
        bytes stay recoverable; reads go dark through the interface because
        get()/read_bytes()/list() honor the registry flag.

        Returns True when the file transitioned to trashed; False when there
        was nothing to do (no registry, unknown id, already trashed).
        """
        if self._registry is None:
            return False
        record = self._registry.get_by_id(attachment_id)
        if record is None or record.trashed_at is not None:
            return False

        now = datetime.now(UTC)
        trash_id = new_id("trash")

        # Retire the live workspace copy; fall back to the mirror blob so the
        # sidecar always carries recoverable bytes.
        data: bytes | None = None
        rel = record.path.replace("\\", "/").lstrip("/")
        live = self._workspace_root / rel
        if live.is_file():
            data = live.read_bytes()
            live.unlink()
        if data is None:
            mirror_blob = self._root / attachment_id / "blob"
            if mirror_blob.is_file():
                data = mirror_blob.read_bytes()

        trash_dir = trash_dir_for(self._workspace_root)
        write_sidecar_pair(
            trash_dir / f"{trash_id}.meta.json",
            trash_dir / f"{trash_id}.blob",
            {
                "trash_id": trash_id,
                "attachment_id": attachment_id,
                "orig_rel_path": rel,
                "trashed_at": now.isoformat(),
                "size_bytes": len(data) if data is not None else 0,
            },
            data or b"",
        )
        self._registry.mark_trashed(record.path, now)
        return True

    def list(self) -> list[StoredFile]:
        """List all stored files, newest first (Workspace SSOT discovery)."""
        found: list[StoredFile] = []
        if not self._root.is_dir():
            return found
        for child in self._root.iterdir():
            if not child.is_dir():
                continue
            stored = self.get(child.name)
            if stored is not None:
                found.append(stored)
        found.sort(key=lambda s: s.attachment_id, reverse=True)
        return found

    def read_text_preview(self, attachment_id: str, *, max_chars: int = 4000) -> str | None:
        data = self.read_bytes(attachment_id)
        if data is None:
            return None
        meta = self.get(attachment_id)
        if meta is None:
            return None
        mime = meta.mime_type.lower().split(";", 1)[0].strip()
        # Hint only — never dump HTML/XML the agent will read via tools.
        if mime in READ_TEXT_PREVIEW_EXCLUDED_MIMES:
            return None
        if not (
            mime.startswith("text/")
            or mime in {"application/json", "application/javascript"}
            or meta.name.lower().endswith((".md", ".txt", ".csv", ".json", ".py", ".ts"))
        ):
            return None
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            return None
        if len(text) > max_chars:
            return text[:max_chars] + "…"
        return text
